-- ============================================================
-- HOMEPAGE SPOTLIGHT TABLE
-- ============================================================
-- Stores the up to 3 images that appear on the homepage showcase.
-- These are uploaded separately from portfolio artworks via the
-- "Homepage Spotlight" section in the admin dashboard.
--
-- Storage: create a NEW bucket called "spotlight" in Supabase Storage
-- (Storage > New bucket > Name: spotlight > Public: ON)

create table if not exists public.homepage_spotlight (
    id bigint generated by default as identity primary key,
    title text not null,
    description text,
    category text not null,
    image_path text not null unique,
    display_order integer not null default 1,
