-- ============================================================
-- TESTIMONIALS TABLE
-- ============================================================

create table if not exists public.testimonials (
    id bigint generated by default as identity primary key,
    name text not null,
    role text not null,
    text text not null,
    rating integer not null default 5 check (rating >= 1 and rating <= 5),
    avatar_url text,
    visible boolean not null default true,
    created_at timestamptz not null default now()
);

alter table public.testimonials enable row level security;

-- Public can read visible testimonials
do $$
begin
    if not exists (
        select 1 from pg_policies
        where schemaname = 'public' and tablename = 'testimonials'
          and policyname = 'Public can read testimonials'
    ) then
        create policy "Public can read testimonials"
        on public.testimonials
        for select
        using (visible = true);
    end if;
end $$;

-- Admin write access (same open policy pattern as artworks)
do $$
begin
    if not exists (
        select 1 from pg_policies
        where schemaname = 'public' and tablename = 'testimonials'
          and policyname = 'Public can insert testimonials'
    ) then
        create policy "Public can insert testimonials"
        on public.testimonials
        for insert
        with check (true);
    end if;
end $$;

do $$
begin
    if not exists (
        select 1 from pg_policies
        where schemaname = 'public' and tablename = 'testimonials'
          and policyname = 'Public can update testimonials'
    ) then
